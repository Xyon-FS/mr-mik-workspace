import assert from 'node:assert/strict';
import { readFile, readdir, lstat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { defaultHubSkillScopes } from '../desktop/service/hub-skill-defaults.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = name => readFile(path.join(root, name), 'utf8');
assert.deepEqual(JSON.parse(await read('workspace/workspace.json')), { entities: [], resources: [] }, 'Distribution must not contain personal or sample cards.');
assert.deepEqual(JSON.parse(await read('projects/registry.json')), { projects: [] });
assert.deepEqual(JSON.parse(await read('projects/skill-defaults.json')), defaultHubSkillScopes, 'Public defaults must not contain personal overrides.');
assert.deepEqual(JSON.parse(await read('.mcp.json')), { mcpServers: {} });
assert.doesNotMatch(await read('.env.example'), /^\w+=(?!\s*$)\S+/m);
assert.match(await read('src/desktop/client.ts'), /defaultBypass: false/);
assert.match(await read('desktop/service/server.mjs'), /defaultBypass: false/);
assert.match(await read('README.md'), /witnesstodark/);
assert.match(await read('LICENSE'), /Copyright/);
await lstat(path.join(root, 'docs/assets/mr-mik.png'));
for (const forbidden of ['.mrmak', '.codex/config.toml', '.claude/settings.local.json', 'projects/skill-scopes.json']) assert.equal(await lstat(path.join(root, forbidden)).catch(() => null), null, `Distribution contains ${forbidden}`);
const names = (await readdir(path.join(root, '.agents/skills'), { withFileTypes: true })).filter(item => item.isDirectory()).map(item => item.name);
const claudeNames = (await readdir(path.join(root, '.claude/skills'), { withFileTypes: true })).filter(item => item.isDirectory()).map(item => item.name);
assert.deepEqual(claudeNames.sort(), [...names].sort(), 'Native skill folder sets must match for Codex and Claude.');
for (const name of ['fal-ai-generation', 'higgsfield-workflow', 'motion-reference-workflow', 'voice-dictation-setup']) assert.ok(names.includes(name), `Missing retained upstream skill: ${name}`);
await lstat(path.join(root, 'knowledge/voice-dictation.md'));
for (const name of names) {
  const source = await read(`.agents/skills/${name}/SKILL.md`);
  assert.match(source, /^---\r?\nname:/);
  assert.equal(await read(`.claude/skills/${name}/SKILL.md`), source);
  assert.doesNotMatch(source, /[A-Z]:[\\/]Users[\\/]/i);
}
console.log(`Clean template passed: no personal cards/projects, ${names.length} maintained skills, no native configuration or local state.`);
