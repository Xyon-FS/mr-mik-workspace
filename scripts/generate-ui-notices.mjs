// Keep the license texts of bundled frontend dependencies in portable/installers.
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const lock = JSON.parse(await readFile(path.join(root, 'package-lock.json'), 'utf8'));
const sections = ['Third-party frontend dependency notices\n\nGenerated by scripts/generate-ui-notices.mjs from package-lock.json.\nDependency code is bundled into the application UI. Each component retains its own license.\n'];
for (const [relative, entry] of Object.entries(lock.packages).sort(([a], [b]) => a.localeCompare(b))) {
  if (!relative || entry.dev || entry.link) continue;
  const folder = path.join(root, relative);
  let names;
  try { names = await readdir(folder); } catch (error) { if (entry.optional && error.code === 'ENOENT') continue; throw error; }
  const pkg = JSON.parse(await readFile(path.join(folder, 'package.json'), 'utf8'));
  sections.push(`\n${'='.repeat(72)}\n${pkg.name} ${pkg.version}\nLicense: ${entry.license || pkg.license || 'See package source'}\n`);
  for (const name of names.filter(name => /^(licen[cs]e|notice|copying)([.-]|$)/i.test(name)).sort()) {
    sections.push(`\n--- ${name} ---\n${await readFile(path.join(folder, name), 'utf8')}\n`);
  }
}
const result = sections.join(''), target = path.join(root, 'desktop/licenses/UI-DEPENDENCIES.txt');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== result) throw new Error('Frontend notices are stale. Run node scripts/generate-ui-notices.mjs.');
} else await writeFile(target, result);
console.log(`Frontend dependency notices ${process.argv.includes('--check') ? 'verified' : 'generated'}.`);
