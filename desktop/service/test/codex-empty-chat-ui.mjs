// Empty-root lifecycle with production UI/service and a synthetic native wire.
import assert from 'node:assert/strict';
import os from 'node:os';
import path from 'node:path';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium, expect } from '@playwright/test';
import { CodexChat } from '../codex-chat.mjs';
import { pooledCodexFixture } from './codex-pooled-fixture.mjs';
import { mkdtemp, createService, cleanupFixtures, testBrowserEnvironment } from './fixtures.mjs';

const base = await mkdtemp(path.join(os.tmpdir(), 'mik-empty-codex-ui-'));
let service, browser;
try {
  const repo = path.join(base, 'hub'), home = path.join(base, 'home');
  await mkdir(path.join(repo, 'workspace'), { recursive: true }); await mkdir(home);
  await writeFile(path.join(repo, 'workspace/workspace.json'), '{"entities":[],"resources":[]}');
  service = await createService({ repo, uiDir: path.resolve('dist'), mcpOptions: { home, env: { CODEX_HOME: home, HOME: home, USERPROFILE: home } } });
  const first = await service.profiles.create('Synthetic A'), second = await service.profiles.create('Synthetic B'), wire = pooledCodexFixture();
  service.sessions.verifyAccount = async () => {}; service.sessions.verifyIdentity = async () => {};
  service.sessions.createGraphicalRuntime = options => new CodexChat({ ...options, workerPool: service.sessions.codexWorkers, spawnChild: wire.spawnChild });
  const source = await service.sessions.create({ agent: 'codex', cwd: repo, accountProfileId: first.id, chatInterface: 'chat', name: 'Empty fixture' });
  const session = service.sessions.get(source.id), originalNativeId = session.nativeId;
  const request = async (action, body = {}) => fetch(service.origin + `/api/sessions/${source.id}/${action}`, { method: 'POST', headers: { Authorization: `Bearer ${service.token}`, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  await request('focus');
  browser = await chromium.launch({ headless: true, channel: 'msedge', env: testBrowserEnvironment() });
  const page = await browser.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(service.urls.chats);
  const chat = page.getByRole('region', { name: 'Codex graphical chat', exact: true });
  const showActions = async () => { await chat.getByLabel('Chat details', { exact: true }).click(); await chat.getByRole('tab', {name:'Actions',exact:true}).click(); };
  await showActions();
  const fork = page.getByRole('button', { name: 'Fork selected conversation', exact: true });
  await expect(fork).toBeDisabled(); await expect(fork).toHaveAttribute('title', /Fork requires an idle/);
  const count = service.sessions.list().length, nativeCalls = wire.calls.length;
  const rejected = await request('fork'); assert.equal(rejected.status, 400);
  assert.match((await rejected.json()).error, /Start a conversation/);
  assert.equal(service.sessions.list().length, count); assert.equal(wire.calls.length, nativeCalls);
  await chat.getByRole('button',{name:'Close chat details',exact:true}).click();
  await chat.getByRole('combobox',{name:'Model and reasoning',exact:true}).click();
  await page.getByRole('combobox',{name:'Codex account',exact:true}).click();
  await page.getByRole('option', { name: 'Synthetic B', exact: true }).click();
  await expect.poll(() => session.accountProfileId).toBe(second.id);
  await expect.poll(() => session.graphical.snapshot().connected).toBe(true);
  await page.keyboard.press('Escape'); await showActions();
  assert.notEqual(session.nativeId, originalNativeId); assert.equal(service.sessions.list().length, count);
  assert.equal(wire.calls.some(call => call.method === 'thread/resume'), false);
  await expect(fork).toBeDisabled();
  await chat.getByRole('button',{name:'Close chat details',exact:true}).click();
  const input = chat.getByRole('textbox', { name: 'Message Codex', exact: true });
  await input.fill('Synthetic local input'); await chat.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect.poll(() => session.graphical.turnId).not.toBeNull();
  await chat.getByRole('button', { name: 'Interrupt response', exact: true }).click();
  await expect.poll(() => session.graphical.snapshot().working).toBe(false);
  await showActions();
  await expect(fork).toBeEnabled();
  const parentId = session.nativeId, response = await request('fork');
  assert.equal(response.status, 201); const branch = await response.json();
  assert.notEqual(branch.nativeId, parentId); assert.equal(session.nativeId, parentId);
  assert.equal(wire.calls.filter(call => call.method === 'turn/start').length, 1);
  assert.deepEqual(errors, []);
  console.log('PASS empty Codex UI: fork disabled/guarded without orphan; account picker rebinds same tab; Send/Stop enable a valid fork; no replay or actual model calls.');
} finally { await browser?.close(); await service?.close(); await cleanupFixtures(); }
