// Isolated production UI. Synthetic protocol only; no login, paid calls or PTY.
import assert from 'node:assert/strict';
import { revealProcessFor } from './chat-disclosure-ui.mjs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { mkdir, writeFile } from 'node:fs/promises';
import { build } from 'vite';
import { chromium, expect } from '@playwright/test';
import { mkdtemp, createService, cleanupFixtures, testBrowserEnvironment } from './fixtures.mjs';
import { CodexChat } from '../codex-chat.mjs';
import { graphicalFixture } from './codex-chat-fixture.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const base = await mkdtemp(path.join(root, '.cache/graphical-operations-ui-'));
let service, browser;
try {
  const repo = path.join(base, 'hub'), home = path.join(base, 'home'), nativeHome = path.join(home, '.codex'), uiDir = path.join(base, 'ui');
  await mkdir(path.join(repo, 'workspace'), { recursive: true }); await mkdir(nativeHome, { recursive: true });
  await writeFile(path.join(repo, 'workspace/workspace.json'), '{"entities":[]}'); await writeFile(path.join(nativeHome, 'config.toml'), '# Synthetic fixture\n');
  await build({ root, configFile: path.join(root, 'vite.config.ts'), logLevel: 'warn', build: { outDir: uiDir, emptyOutDir: false } });
  service = await createService({ repo, uiDir, mcpOptions: { home, env: { ...process.env, CODEX_HOME: nativeHome } }, profileOptions: { root: path.join(base, 'accounts') } });
  const profile = await service.profiles.create('Operations fixture');
  service.sessions.verifyAccount = async () => {}; service.sessions.verifyIdentity = async () => {}; service.sessions.captureTools = async () => ({}); service.accounts.status = async () => 'logged-in';
  const transport = graphicalFixture({ approval: true });
  service.sessions.createGraphicalRuntime = options => new CodexChat({ ...options, spawnChild: transport.spawnChild });
  const session = await service.sessions.create({ agent: 'codex', name: 'Operations fixture', chatInterface: 'chat', accountProfileId: profile.id, codexPermissions: 'auto-review', effort: 'medium', cwd: repo });
  const runtime = service.sessions.get(session.id).graphical, child = transport.children[0];
  browser = await chromium.launch({ env: testBrowserEnvironment(), headless: true, channel: process.env.MRMAK_TEST_BROWSER || 'msedge' });
  const page = await browser.newPage({ viewport: { width: 650, height: 1050 } }), errors = [];
  page.on('pageerror', error => errors.push(error.message)); await page.goto(service.urls.chats);
  const chat = page.getByRole('region', { name: 'Codex graphical chat', exact: true }); await expect(chat).toBeVisible();
  const context = chat.locator('.graphical-usage'), details = chat.locator('.graphical-details');
  await chat.getByLabel('Chat details', { exact: true }).click(); await expect(context.locator('summary')).toHaveCount(0); await expect(details).toHaveAttribute('open');
  await details.getByRole('tab', { name: 'Context', exact: true }).click();
  await context.getByRole('button', { name: 'Compact context', exact: true }).click();
  await expect(context).toContainText('account allowance');
  await context.getByRole('button', { name: 'Start compaction', exact: true }).click();
  await expect.poll(() => runtime.operations.snapshot()?.status).toBe('running');
  await chat.getByRole('combobox', { name: 'Model and reasoning', exact: true }).click();
  await expect(page.getByRole('dialog',{name:'Model and reasoning',exact:true}).getByRole('combobox',{name:'Model',exact:true})).toBeDisabled();
  await page.keyboard.press('Escape');
  assert.equal(transport.calls.filter(call => call.method === 'thread/compact/start').length, 1);
  child.finishOperation(); await expect.poll(() => runtime.operations.snapshot()?.status).toBe('completed');
  await expect(chat.locator('.graphical-turn-process').last().locator(':scope > summary')).toContainText('Worked');
  await expect(chat.locator('.graphical-turn-process').last()).not.toHaveAttribute('open');
  await expect(chat.locator('.graphical-operation-status')).toContainText('compaction completed');
  await chat.getByLabel('Chat details', { exact: true }).click();
  await details.getByRole('tab', { name: 'Session', exact: true }).click(); await details.getByRole('button', { name: 'Review changes', exact: true }).click();
  await details.getByRole('combobox', { name: 'Review scope', exact: true }).click();
  await page.getByRole('option', { name: 'Against a branch', exact: true }).click();
  await expect(details).toHaveAttribute('open');
  await details.getByRole('textbox', { name: 'Base branch', exact: true }).fill('main');
  const bounds = await details.locator(':scope > div').boundingBox(); assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 650);
  await page.screenshot({ path: path.join(root, '.cache/codex-chat-review-controls.png') });
  await details.getByRole('button', { name: 'Start review', exact: true }).click();
  await expect.poll(() => runtime.operations.snapshot()?.kind).toBe('review');
  await expect.poll(() => runtime.operations.snapshot()?.status).toBe('running');
  assert.deepEqual(transport.calls.find(call => call.method === 'review/start').params.target, { type: 'baseBranch', branch: 'main' });
  child.finishOperation(); await expect.poll(() => runtime.operations.snapshot()?.status).toBe('completed');
  await expect(chat.locator('.graphical-turn-process').last().locator(':scope > summary')).toContainText('Worked');
  await expect(chat.locator('.graphical-turn-process').last()).not.toHaveAttribute('open');
  await chat.locator('.graphical-messages').click({ position: { x: 10, y: 10 } });
  await revealProcessFor(chat.locator('.graphical-work-group').last()); await chat.locator('.graphical-work-group').last().locator(':scope > summary').click();
  await expect(chat.getByRole('region', { name: 'Review results', exact: true })).toContainText('no actionable findings');
  transport.history.set('fixture-child', [{ id: 'child-result', type: 'agentMessage', text: 'Agent inspected the source.' }]);
  child.notify('item/completed', { threadId: runtime.threadId, turnId: 'agent-parent-turn', item: { id: 'child-call', type: 'collabAgentToolCall', tool: 'spawnAgent', status: 'completed', receiverThreadIds: ['fixture-child'], agentsStates: { 'fixture-child': { status: 'completed', message: 'Inspection finished.' } }, prompt: 'Inspect source' } });
  await expect(chat.getByRole('region', { name: 'Subagents', exact: true })).toBeVisible();
  const group = chat.locator('.graphical-work-group').last();
  await revealProcessFor(group);
  if (!(await group.getAttribute('open'))) await group.locator(':scope > summary').click();
  await expect(chat.locator('.graphical-agents')).toHaveCount(1);
  await chat.getByRole('button', { name: 'View agent', exact: true }).click();
  const agent = page.getByRole('dialog', { name: 'Agent conversation', exact: true });
  await expect(agent).toContainText('Fixture agent'); await expect(agent).toContainText('Agent inspected the source.');
  await expect(agent.getByRole('textbox')).toHaveCount(0);
  const agentBounds = await agent.boundingBox(); assert.ok(agentBounds.x >= 8 && agentBounds.y >= 8 && agentBounds.x + agentBounds.width <= 650 && agentBounds.y + agentBounds.height <= 1050);
  await page.screenshot({ path: path.join(root, '.cache/codex-chat-agent-reader.png') });
  await agent.press('Escape'); await expect(agent).toHaveCount(0);
  child.request(901, 'item/commandExecution/requestApproval', { threadId: 'fixture-child', turnId: 'child-turn', command: 'Synthetic child approval', reason: 'Explicit subagent approval fixture' });
  await expect(chat).toContainText('Synthetic child approval');
  await chat.getByRole('button', { name: 'Decline', exact: true }).click();
  await expect.poll(() => transport.calls.find(call => call.id === 901 && !call.method)?.result?.decision).toBe('decline');
  child.notify('serverRequest/resolved', { requestId: 901 });
  await expect.poll(() => runtime.requests.size).toBe(0);
  assert.equal(runtime.turnId, null);
  await chat.getByLabel('Chat details', { exact: true }).click();
  await details.getByRole('tab', { name: 'Context', exact: true }).click();
  await chat.locator('.graphical-operation-status').getByRole('button', { name: 'Dismiss', exact: true }).click();
  await expect(chat.locator('.graphical-operation-status')).toHaveCount(0);
  assert.equal(transport.calls.some(call => ['thread/resume', 'turn/start'].includes(call.method)), false);
  assert.equal(runtime.session.codexPermissions, 'auto-review'); assert.equal(runtime.session.accountProfileId, profile.id);
  assert.deepEqual(errors, []);
  console.log('PASS: explicit compaction/review, native outcome, blocked controls, nested scope dropdown, 650px layout, review output, read-only agent navigation and routed child approval/decline. No real account or model calls.');
} finally { await browser?.close(); await service?.close(); await cleanupFixtures(); }
