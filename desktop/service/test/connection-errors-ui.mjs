import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { mkdir, writeFile } from 'node:fs/promises';
import { build } from 'vite';
import { chromium, expect } from '@playwright/test';
import { mkdtemp, createService, cleanupFixtures, testBrowserEnvironment } from './fixtures.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const base = await mkdtemp(path.join(root, '.cache/connection-ui-'));
let service, browser;
try {
  const repo = path.join(base, 'hub'), linked = path.join(base, 'project'), home = path.join(base, 'home'), uiDir = path.join(base, 'ui');
  await build({ root, configFile: path.join(root, 'vite.config.ts'), logLevel: 'warn', build: { outDir: uiDir, emptyOutDir: false } });
  for (const folder of [path.join(repo, 'workspace'), path.join(linked, '.codex'), home]) await mkdir(folder, { recursive: true });
  await writeFile(path.join(repo, 'workspace/workspace.json'), '{"entities":[]}');
  await writeFile(path.join(linked, '.codex/config.toml'), '[mcp_servers.fixture]\ncommand="C:/missing/fixture.exe"\n');
  service = await createService({ repo, uiDir, mcpOptions: { home, env: {} } });
  const project = await service.projects.save({ name: 'Connection fixture', repositoryPath: linked });
  const headers = { Authorization: `Bearer ${service.token}`, 'Content-Type': 'application/json' };
  await fetch(`${service.origin}/api/settings`, { method: 'POST', headers, body: JSON.stringify({ selectedProjectId: project.id }) });
  service.coordinator.start = async () => { throw Object.assign(new Error('private-provider-details'), { statusCode: 503 }); };
  const operation = await service.coordinator.ask({ id: 'fixture-failure', text: 'Synthetic failed request', scope: { projectId: project.id } });
  assert.equal(operation.connectionIssue.category, 'remote-unreachable');
  assert.ok(!JSON.stringify(operation).includes('private-provider-details'));
  let retries = 0;
  service.coordinator.start = async () => { retries++; };
  service.coordinator.ensureThread = async () => {};
  browser = await chromium.launch({ env: testBrowserEnvironment(), headless: true, channel: process.env.MRMAK_TEST_BROWSER || 'msedge' });
  const page = await browser.newPage({ viewport: { width: 1200, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.route('**/api/reasoning**', route => route.fulfill({ json: { codex: { model: 'fixture', efforts: ['medium'], models: [{ model: 'fixture', label: 'Fixture' }] }, codexWorker: { efforts: ['medium'] }, claude: { efforts: ['high'] } } }));
  await page.goto(service.urls.workspace);
  await page.getByRole('button', { name: 'Toggle projects' }).click();
  await expect(page.getByRole('button', { name: 'Check linked project tools' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Toggle mcp' }).click();
  await page.route('**/api/browser-settings', route => route.request().method() === 'POST' ? route.abort('failed') : route.continue());
  await page.getByRole('combobox', { name: 'Browser availability', exact: true }).click();
  await page.getByRole('option', { name: 'Enabled', exact: true }).click();
  await expect(page.locator('.managed-browser-tools [role="alert"]')).toContainText('local Mr. Mik service');
  await page.unroute('**/api/browser-settings');
  await page.getByRole('button', { name: 'Toggle Mik', exact: true }).click();
  await expect(page.locator('.mak-answer')).toContainText('agent service could not be reached');
  await page.getByRole('textbox', { name: 'Message Mik' }).fill('Preserved unsent draft');
  await page.getByRole('button', { name: 'Retry connection', exact: true }).click();
  await expect(page.getByText('Agent connection is ready. No previous request or action was resent.', { exact: true })).toBeVisible();
  assert.equal(await page.getByRole('textbox', { name: 'Message Mik' }).inputValue(), 'Preserved unsent draft');
  assert.equal(retries, 1); assert.equal(service.coordinator.operations.size, 1);
  assert.equal(service.sessions.list().length, 0); assert.equal(service.coordinator.child, null);
  assert.deepEqual(errors, []);
  console.log('PASS: obsolete preflight action absent, descriptive local/provider errors and connection-only retry preserve the draft and do not replay the failed operation. No native agent started.');
} finally { await browser?.close(); await service?.close(); await cleanupFixtures(); }
