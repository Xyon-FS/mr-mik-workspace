export async function seedWorkspaceFiles(service, repo, base) {
  const external = path.join(base, 'External'), secondary = path.join(base, 'Secondary'), another = path.join(base, 'Another'), fresh = path.join(base, 'Fresh');
  for (const folder of [external, secondary, another, fresh]) await mkdir(folder, { recursive: true });
  const source = path.join(external, 'library.md'); await writeFile(source, '# Library fixture');
  const project = await service.projects.save({ name: 'Workspace fixture', repositoryPath: external });
  const other = await service.projects.save({ name: 'Other workspace', repositoryPath: another });
  const linked = await service.projects.saveRepository({ projectId: project.id, name: 'Secondary', repositoryPath: secondary });
  await service.projects.createCard({ projectId: project.id, repositoryId: linked.id, title: 'Review notes' });
  await service.projects.importResource({ kind: 'knowledge', projectId: project.id, source });
  const process = path.join(external, 'release.md'); await writeFile(process, '# Release fixture');
  await service.projects.importResource({ kind: 'process', projectId: project.id, source: process });
  await writeFile(path.join(repo, 'inbox/reference.txt'), 'original reference');
  await service.projects.assignResource({ kind: 'inbox', path: 'inbox/reference.txt', projectId: project.id });
  return { project, other, linked, source, repo, service, fresh };
}

