import test from 'node:test';
import assert from 'node:assert/strict';
import os from 'node:os';
import path from 'node:path';
import { mkdir, realpath, symlink, writeFile } from 'node:fs/promises';
import { chatBlockPreview } from '../chat-block-preview.mjs';
import { mkdtemp } from './fixtures.mjs';
import { visualizeReference } from '../chat-visualize.mjs';
const session = { id: 'session', agent: 'claude', chatInterface: 'chat' };
const runtime = { runtimeId: 'runtime', items: new Map([['answer', { text: '```html\n<script>doNotExecute()</script>\n```\n|Name|Value|\n|---|---|\n|A|B|' }]]), historyItems: new Map() };
test('block previews are deterministic, scoped text snapshots rather than executable documents', async () => {
  const input = { itemId: 'answer', kind: 'code', language: 'html', text: '<script>doNotExecute()</script>' };
  const preview = await chatBlockPreview(session, runtime, input);
  assert.equal(preview.kind, 'rich'); assert.equal(preview.path, ''); assert.equal(preview.text, input.text);
  assert.equal(preview.identity, (await chatBlockPreview(session, runtime, input)).identity);
  assert.notEqual(preview.identity, (await chatBlockPreview({ ...session, id: 'other' }, runtime, input)).identity);
  await assert.rejects(chatBlockPreview(session, runtime, { ...input, runtimeId: 'old' }), /changed/);
  await assert.rejects(chatBlockPreview(session, runtime, { ...input, text: 'fabricated' }));
  await assert.rejects(chatBlockPreview(session, runtime, { ...input, language: 'html\n```' }));
  await assert.rejects(chatBlockPreview({ ...session, chatInterface: 'cli' }, runtime, input));
  const quoted = { ...runtime, items: new Map([['quote', { text: '> ```js\r\n> const one = 1;\r\n> console.log(one);\r\n> ```' }]]) };
  assert.equal((await chatBlockPreview(session, quoted, { itemId: 'quote', kind: 'code', language: 'js', text: 'const one = 1;\nconsole.log(one);' })).text, 'const one = 1;\nconsole.log(one);');
});
test('visualize previews load only recorded HTML within the linked scope', async () => {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'mik-visualize-'));
  const cwd = path.join(dir, 'project'), repo = path.join(dir, 'hub');
  await mkdir(cwd); await mkdir(repo);
  const file = path.join(cwd, 'my concept.html'), outside = path.join(dir, 'outside.html');
  const marker = file => `\uE200visualize\uE202${JSON.stringify({path: file, mode: 'wide', title: 'Example'})}\uE201`;
  const message = { type: 'agentMessage', text: `Intro\n\n${marker(file)}` };
  const input = { itemId: 'concept', kind: 'visualize', visualizePath: file };
  const source = { ...runtime, items: new Map([['concept', message]]) };
  const linked = { ...session, cwd };
  const html = '<main><h1>Example</h1></main><script>document.title="Local";</script>';
  await writeFile(file, html); await writeFile(outside, html);
  assert.deepEqual(visualizeReference(marker(file)), { path: file, wide: true, title: 'Example' });
  assert.equal(visualizeReference('https://example.invalid/'), null);
  const initial = await chatBlockPreview(linked, source, input, repo);
  assert.equal(initial.disk.file, await realpath(file));
  assert.equal(initial.text, undefined);
  await assert.rejects(chatBlockPreview(linked, source, { ...input, visualizePath: outside }, repo), /not recorded/);
  message.text = marker(outside);
  await assert.rejects(chatBlockPreview(linked, source, { ...input, visualizePath: outside }, repo), /unavailable/);
  if (process.platform === 'win32') await symlink(dir, path.join(cwd, 'outside'), 'junction');
  else await symlink(dir, path.join(cwd, 'outside'), 'dir');
  const escaped = path.join(cwd, 'outside', 'outside.html');
  message.text = marker(escaped);
  await assert.rejects(chatBlockPreview(linked, source, { ...input, visualizePath: escaped }, repo), /unavailable/);
  message.text = marker(file);
  message.type = 'userMessage';
  await assert.rejects(chatBlockPreview(linked, source, input, repo), /not recorded/);
  message.type = 'agentMessage';
  const inline = { ...input, inline: true };
  await writeFile(file, 'é'.repeat(500000));
  assert.equal((await chatBlockPreview(linked, source, inline, repo)).disk.info.size, 1000000);
  await writeFile(file, 'é'.repeat(500000) + 'x');
  assert.deepEqual(await chatBlockPreview(linked, source, inline, repo), { workspaceOnly: true });
  const large = await chatBlockPreview(linked, source, input, repo);
  assert.equal(large.disk.info.size, 1000001);
  assert.equal(large.text, undefined);
  assert.equal((await chatBlockPreview(linked, source, { ...inline, identity: large.identity }, repo)).identity, large.identity);
  await assert.rejects(chatBlockPreview(linked, source, { ...inline, identity: initial.identity }, repo), /changed/);
});
